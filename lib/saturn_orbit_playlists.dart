/// Shared, manually ordered movie playlists stored in the existing
/// SATURN ritualOps document. Each playlist and each film has its OWN
/// updatedAt/tombstone so independent edits safely merge between devices.
///
/// Playlists do not imply watch order, release order, MCU chronology or
/// membership of Nossa Órbita's ordinary watchlist. Their order is the
/// order the couple actually chooses.
class SaturnFilmPlaylist {
  const SaturnFilmPlaylist({
    required this.id, required this.name, required this.createdAt,
  });
  final String id;
  final String name;
  final int createdAt;
}

class SaturnPlaylistFilm {
  const SaturnPlaylistFilm({required this.workId, required this.position});
  final String workId;
  final int position;
}

class SaturnOrbitPlaylists {
  const SaturnOrbitPlaylists._();

  static const definitionPrefix = 'playlist:def:';
  static const itemPrefix = 'playlist:item:';

  static int _number(Object? value) => value is num ? value.toInt() : 0;
  static Map<String, dynamic> _row(Object? value) =>
      value is Map ? Map<String, dynamic>.from(value) : <String, dynamic>{};

  static String cleanName(String title) {
    final clean = title.trim().replaceAll(RegExp(r'\s+'), ' ');
    return clean.length <= 64 ? clean : clean.substring(0, 64);
  }

  static List<SaturnFilmPlaylist> playlists(Map<String, dynamic> ops) {
    final output = <SaturnFilmPlaylist>[];
    for (final entry in ops.entries) {
      if (!entry.key.startsWith(definitionPrefix)) continue;
      final row = _row(entry.value);
      if (row['present'] != true) continue;
      final id = entry.key.substring(definitionPrefix.length);
      final name = cleanName((row['name'] ?? '').toString());
      if (id.isEmpty || name.isEmpty) continue;
      output.add(SaturnFilmPlaylist(
        id: id, name: name, createdAt: _number(row['createdAt']),
      ));
    }
    output.sort((a, b) {
      final byDate = a.createdAt.compareTo(b.createdAt);
      return byDate != 0 ? byDate : a.id.compareTo(b.id);
    });
    return output;
  }

  static bool exists(Map<String, dynamic> ops, String id) =>
      _row(ops['$definitionPrefix$id'])['present'] == true;

  static List<SaturnPlaylistFilm> films(
      Map<String, dynamic> ops, String playlistId) {
    if (!exists(ops, playlistId)) return const [];
    final prefix = '$itemPrefix$playlistId:';
    final output = <SaturnPlaylistFilm>[];
    for (final entry in ops.entries) {
      if (!entry.key.startsWith(prefix)) continue;
      final row = _row(entry.value);
      if (row['present'] != true) continue;
      final workId = (row['workId'] ?? entry.key.substring(prefix.length))
          .toString();
      if (workId.isEmpty) continue;
      output.add(SaturnPlaylistFilm(
          workId: workId, position: _number(row['position'])));
    }
    output.sort((a, b) {
      final p = a.position.compareTo(b.position);
      return p != 0 ? p : a.workId.compareTo(b.workId);
    });
    return output;
  }

  /// Call with a unique ID generated by the caller; the helper never
  /// substitutes a saved user's ID or invents a movie.
  static bool create(Map<String, dynamic> ops, {
    required String id, required String name, required int at,
  }) {
    final title = cleanName(name);
    if (id.isEmpty || id.contains(':') || title.isEmpty ||
        ops.containsKey('$definitionPrefix$id')) return false;
    ops['$definitionPrefix$id'] = {
      'name': title, 'present': true, 'createdAt': at, 'updatedAt': at,
    };
    return true;
  }

  static bool rename(Map<String, dynamic> ops, String id,
      String name, int at) {
    final title = cleanName(name);
    if (!exists(ops, id) || title.isEmpty) return false;
    final key = '$definitionPrefix$id';
    final row = _row(ops[key]);
    ops[key] = {
      ...row, 'name': title, 'updatedAt': _fresh(at, _number(row['updatedAt'])),
    };
    return true;
  }

  static int _fresh(int at, int prior) => at > prior ? at : prior + 1;

  static bool delete(Map<String, dynamic> ops, String id, int at) {
    if (!exists(ops, id)) return false;
    final key = '$definitionPrefix$id';
    final row = _row(ops[key]);
    ops[key] = {
      ...row, 'present': false,
      'updatedAt': _fresh(at, _number(row['updatedAt'])),
    };
    // Keep movie tombstones and old snapshots. No data is purged from the
    // shared Supabase document or from either person's ratings.
    return true;
  }

  static bool add(Map<String, dynamic> ops, String id,
      String workId, int at) {
    if (!exists(ops, id) || workId.trim().isEmpty) return false;
    if (films(ops, id).any((item) => item.workId == workId)) return false;
    final items = films(ops, id);
    final maxPosition = items.isEmpty ? -1 :
        items.map((item) => item.position).reduce(
            (a, b) => a > b ? a : b);
    final key = '$itemPrefix$id:$workId';
    final old = _row(ops[key]);
    ops[key] = {
      ...old,
      'workId': workId, 'position': maxPosition + 1,
      'present': true,
      'updatedAt': _fresh(at, _number(old['updatedAt'])),
    };
    return true;
  }

  static bool remove(Map<String, dynamic> ops, String id,
      String workId, int at) {
    if (!exists(ops, id)) return false;
    final key = '$itemPrefix$id:$workId';
    final row = _row(ops[key]);
    if (row['present'] != true) return false;
    ops[key] = {
      ...row, 'present': false,
      'updatedAt': _fresh(at, _number(row['updatedAt'])),
    };
    return true;
  }

  /// Persist an exact order, regardless of release, narrative timeline,
  /// franchise or the order in which the user originally saved each film.
  /// Each movie row is individually stamped for the existing cloud merger.
  static bool reorder(Map<String, dynamic> ops, String id,
      List<String> orderedWorkIds, int at) {
    if (!exists(ops, id)) return false;
    final before = films(ops, id).map((i) => i.workId).toList();
    if (before.length != orderedWorkIds.length ||
        orderedWorkIds.toSet().length != before.length ||
        !before.toSet().containsAll(orderedWorkIds)) return false;
    if (_same(before, orderedWorkIds)) return false;
    var clock = at;
    for (final workId in orderedWorkIds) {
      final previous = _row(ops['$itemPrefix$id:$workId']);
      final oldAt = _number(previous['updatedAt']);
      if (clock <= oldAt) clock = oldAt + 1;
    }
    for (var index = 0; index < orderedWorkIds.length; index++) {
      final key = '$itemPrefix$id:${orderedWorkIds[index]}';
      final row = _row(ops[key]);
      ops[key] = {...row, 'position': index, 'updatedAt': clock + index};
    }
    return true;
  }

  static bool _same(List<String> a, List<String> b) {
    if (a.length != b.length) return false;
    for (var i = 0; i < a.length; i++) {
      if (a[i] != b[i]) return false;
    }
    return true;
  }
}
